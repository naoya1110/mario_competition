"""Competition settings shared by 01_collect_data, 02_review_data and 04_playagent.

==========================================================================
DO NOT EDIT THIS FILE.
  The values and formula here are the competition rules. They make sure
  every team is scored under the same conditions. If you change them,
  your AI may act at a different frame rate from your training data, and
  your Skill score can no longer be compared with other teams.
  (Settings you may tune, such as STACK_SIZE, are in the notebooks.)
==========================================================================
"""

# Frames are saved (01) and actions are chosen (04) at this rate. The two must
# match so that the agent acts at the same frame interval it was trained on.
TARGET_FPS = 30

# --- Skill score ------------------------------------------------------------
X_GOAL = 3161  # x position of the flagpole in world 1-1
START_TIME = 400  # the in-game timer every episode starts from
T_FAST = 110  # full speed score at or below this time
T_SLOW = 260  # zero speed score at or above this time
SCORE_TARGET = 5000  # full points term at this in-game score
SKILL_WEIGHTS = {"progress": 0.40, "clear": 0.10, "speed": 0.20, "points": 0.30}


def skill_terms(row) -> dict:
    """The four components of the Skill score for one episode, each in 0-1.

    `row` needs x_pos_max, flag_get, time_remaining and score. Speed and points
    only count for cleared episodes: dying quickly is not skill, and a clear is
    what earns the bonus for playing it well.
    """
    clear = 1.0 if row["flag_get"] else 0.0
    t_used = START_TIME - row["time_remaining"]
    return {
        "progress": min(row["x_pos_max"] / X_GOAL, 1.0),
        "clear": clear,
        "speed": clear * min(max((T_SLOW - t_used) / (T_SLOW - T_FAST), 0.0), 1.0),
        "points": clear * min(row["score"] / SCORE_TARGET, 1.0),
    }


def skill_score(row) -> float:
    """Overall 0-100 rating of one episode."""
    terms = skill_terms(row)
    return 100 * sum(SKILL_WEIGHTS[name] * value for name, value in terms.items())


def add_skill_score(df):
    """Return a copy of a per-episode DataFrame with the Skill score and its terms added.

    Built on skill_terms() so the formula exists in one place only.
    """
    out = df.copy()
    out["t_used"] = START_TIME - out["time_remaining"]
    terms = [skill_terms(row) for row in df.to_dict("records")]
    for name in SKILL_WEIGHTS:
        out[name] = [t[name] for t in terms]
    out["skill"] = [100 * sum(SKILL_WEIGHTS[k] * t[k] for k in SKILL_WEIGHTS) for t in terms]
    return out
